// Builds docs/presentation/enterprise-observability.pptx and speaker-notes.md.
//
//   node docs/presentation/build.js
//
// pptxgenjs is not vendored in this repository; install it wherever you run
// the build (npm install pptxgenjs) and set NODE_PATH if it lives elsewhere.
const path = require("path");
const fs = require("fs");
const PptxGenJS = require("pptxgenjs");
const L = require("./lib");

const OUT = path.join(__dirname, "enterprise-observability.pptx");
const NOTES_OUT = path.join(__dirname, "speaker-notes.md");

const pptx = new PptxGenJS();
pptx.layout = "LAYOUT_WIDE";
pptx.author = "observability-platform";
pptx.company = "Enterprise Observability Programme";
pptx.title = "Enterprise Observability — executive briefing";
pptx.subject = "Policy-as-data monitoring on Datadog: what is shipped, what is not, and what happens next";

require("./part1").build(pptx);
require("./part2").build(pptx);
require("./part3").build(pptx);
require("./part4").build(pptx);
require("./part5").build(pptx);

pptx.writeFile({ fileName: OUT }).then(() => {
  const lines = [];
  lines.push("# Speaker notes — Enterprise Observability executive briefing");
  lines.push("");
  lines.push("Companion to [`enterprise-observability.pptx`](enterprise-observability.pptx).");
  lines.push("Both files are generated by `build.js` in this directory; edit the generator, not the outputs.");
  lines.push("");
  lines.push("**The delivery contract for this deck:** every figure comes from the repository or the");
  lines.push("last production deploy. Anything not shipped is labelled ROADMAP with its phase.");
  lines.push("If a question exposes a gap, answer with the gap — the appendix carries the full register.");
  lines.push("");
  lines.push(`**${L.NOTES.length} slides.** Main deck slides 1–43; appendix 44–${L.NOTES.length}.`);
  lines.push("");
  lines.push("---");
  lines.push("");
  L.NOTES.forEach((n) => {
    lines.push(`## Slide ${n.n} — ${n.title.replace(/\n/g, " ")}`);
    lines.push("");
    const body = (n.notes || "_No notes._").trim();
    body.split(/\n\n+/).forEach((para) => {
      lines.push(para.replace(/\n/g, " ").trim());
      lines.push("");
    });
    lines.push("---");
    lines.push("");
  });
  fs.writeFileSync(NOTES_OUT, lines.join("\n"));
  console.log(`wrote ${OUT} (${L.NOTES.length} slides)`);
  console.log(`wrote ${NOTES_OUT}`);
}).catch((e) => {
  console.error(e);
  process.exit(1);
});
